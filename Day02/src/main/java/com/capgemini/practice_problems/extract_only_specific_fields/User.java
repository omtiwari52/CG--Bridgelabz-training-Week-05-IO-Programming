package com.capgemini.practice_problems.extract_only_specific_fields;

public class User {

    private String name;
    private String email;
    private int age;
    private String city;

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }

    public String getCity() {
        return city;
    }

    public String getEmail() {
        return email;
    }
}
